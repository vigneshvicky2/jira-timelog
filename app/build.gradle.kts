// Release signing key lives outside the repo (never committed). Point TIMELOG_SIGNING at a
// properties file with storeFile/storePassword/keyAlias/keyPassword, or use the default location.
// Without it, release builds fall back to the local debug key so anyone can still build.
val signingProps = Properties().also { props ->
    val path = System.getenv("TIMELOG_SIGNING")
        ?: "${System.getProperty("user.home")}/.android-keys/timelog.properties"
    val f = file(path)
    if (f.exists()) f.inputStream().use { props.load(it) }
}

android {
    namespace = "io.github.vigneshvicky2.timelog"
    compileSdk = 36

    defaultConfig {
        applicationId = "io.github.vigneshvicky2.timelog"
        minSdk = 31
        targetSdk = 36
        versionCode = 1
        versionName = "1.0.0"
    }

    signingConfigs {
        if (signingProps.isNotEmpty()) {
            create("release") {
                storeFile = file(signingProps.getProperty("storeFile"))
                storePassword = signingProps.getProperty("storePassword")
                keyAlias = signingProps.getProperty("keyAlias")
                keyPassword = signingProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"))
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures { compose = true }
}

